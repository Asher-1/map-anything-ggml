#!/usr/bin/env python3
"""Build benchmarks/results/eval_eth3d_matrix.md from the per-version eval
files (eval_eth3d_<version>.md written by scripts/eval_cpp_cli.py, typically
via scripts/rerun_eval_matrix.sh).

Usage: python3 benchmarks/build_matrix_md.py [--results benchmarks/results]
"""
import argparse
from pathlib import Path

# column order: per model, torch adjudication baseline + supported quants
VERSIONS = [
    ("512_torch", "PyTorch-CUDA 512 (official)"),
    ("512_f16", "ggml CUDA 512 f16"),
    ("512_q8_0", "ggml CUDA 512 q8_0"),
    ("512_q5_K", "ggml CUDA 512 q5_K"),
    ("416_torch", "PyTorch-CUDA 416-reproduce (official)"),
    ("416_f16", "ggml CUDA 416 f16"),
    ("416_q8_0", "ggml CUDA 416 q8_0"),
    ("416_q5_K", "ggml CUDA 416 q5_K"),
    ("text_torch", "PyTorch-CUDA 256-text (official)"),
    ("text_f16", "ggml CUDA 256-text f16"),
    ("text_q8_0", "ggml CUDA 256-text q8_0"),
    ("text_q5_K", "ggml CUDA 256-text q5_K"),
]
SECTIONS = [
    ("Depth (normalized z-depth)",
     ["AbsRel", "SqRel", "RMSE", "RMSE-log", "d1", "d2", "d3"]),
    ("Pose (view0-frame relative pose)",
     ["rot_err_deg", "center_err", "ATE"]),
    ("Pose AUC", ["AUC@1", "AUC@5", "AUC@15", "AUC@30"]),
    ("Point cloud (camera-frame Chamfer family)",
     ["chamfer", "accuracy", "completeness", "fscore"]),
    ("Intrinsics (FOV/f)",
     ["fov_err_deg", "fov_x_err_deg", "fov_y_err_deg", "fx_err", "fy_err"]),
]
# torch-vs-cpp-f16 consistency summary; continuous quantities use relative
# diff, discrete/scale-sensitive ones (AUC window counts, AbsRel whose gap is
# the known GT-border artifact, chamfer) use absolute diff
FAMILIES = [("pose family", ["rot_err_deg", "center_err", "ATE"], "rel"),
            ("FOV angle family", ["fov_err_deg", "fov_x_err_deg", "fov_y_err_deg"], "rel"),
            ("fx/fy", ["fx_err", "fy_err"], "rel")]


def parse_eval_md(path):
    """Parse '| metric | value |' rows (same format as
    scripts/compare_reconstruction.parse_eval_md)."""
    out = {}
    for line in Path(path).read_text().splitlines():
        parts = [p.strip() for p in line.strip("|").split("|")]
        if len(parts) == 2 and parts[1].replace(".", "").replace("-", "")\
                .isdigit():
            out[parts[0]] = float(parts[1])
    return out


def rel_diff(a, b):
    if a == b:
        return 0.0
    d = abs(a - b) / max(abs(a), abs(b), 1e-12)
    return d


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=str(
        Path(__file__).resolve().parent / "results"))
    args = ap.parse_args()
    res = Path(args.results)

    data, missing = {}, []
    for v, _ in VERSIONS:
        p = res / f"eval_eth3d_{v}.md"
        if p.exists():
            data[v] = parse_eval_md(p)
        else:
            missing.append(v)

    lines = [
        "# ETH3D official-protocol evaluation matrix — all model versions x PyTorch-CUDA baseline",
        "",
        "- Protocol: MapAnything ETH3D (avg_dis scale normalization · view0 frame · 13 windows x 2 views)",
        "- Resolution: 512 model 512x336 / 416 model 416x272 / 256-text model 256x176"
        " (each model's official 1:1.52 AR setting)",
        "- One metric implementation (mapanything.utils.metrics + this script's"
        " extension columns) feeds both runtimes' outputs",
        "- torch = official model (CUDA, adjudication baseline); ggml = vggt-cli (CUDA backend)",
        "- q4_K removed (2026-09-18, see RESULTS.md §6); generated by"
        " `scripts/build_matrix_md.py`",
        "",
    ]
    for title, keys in SECTIONS:
        lines += [f"## {title}", ""]
        lines.append("| metric | " + " | ".join(n for _, n in VERSIONS) + " |")
        lines.append("|" + "------|" * (len(VERSIONS) + 1))
        for k in keys:
            row = [k]
            for v, _ in VERSIONS:
                val = data.get(v, {}).get(k)
                row.append("—" if val is None else f"{val:.5f}")
            lines.append("| " + " | ".join(row) + " |")
        lines.append("")

    # per-model torch vs ggml-f16 consistency summary
    lines += ["## Dual-runtime consistency (torch vs ggml f16, same model)", "",
              "Continuous quantities use relative diff; the AbsRel/chamfer/d1"
              " absolute diffs reflect the known GT-invalid-border divergence"
              " (see RESULTS.md §3), not porting errors.", ""]
    lines.append("| model | pose-family max rel diff | FOV-angle family max rel diff | fx/fy max rel diff "
                 "| dAbsRel | dchamfer | dd1 |")
    lines.append("|------|------------------|----------------------|"
                 "------------------|---------|----------|-----|")
    for model in ("512", "416", "text"):
        t, c = data.get(f"{model}_torch"), data.get(f"{model}_f16")
        if not t or not c:
            lines.append(f"| {model} | — | — | — | — | — | — |")
            continue
        cells = []
        for _, keys, mode in FAMILIES:
            m = max(rel_diff(t.get(k, 0), c.get(k, 0)) for k in keys
                    if k in t and k in c) * 100
            cells.append(f"{m:.4f}%")
        dabs = lambda k: abs(t.get(k, 0) - c.get(k, 0))
        lines.append(f"| {model} | {cells[0]} | {cells[1]} | {cells[2]} | "
                     f"{dabs('AbsRel'):.5f} | {dabs('chamfer'):.5f} | "
                     f"{dabs('d1'):.5f} |")
    lines.append("")

    if missing:
        lines.append(f"(missing versions: {', '.join(missing)})")
        lines.append("")
    out = res / "eval_eth3d_matrix.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({len(VERSIONS) - len(missing)}/{len(VERSIONS)} "
          "versions)")


if __name__ == "__main__":
    main()
